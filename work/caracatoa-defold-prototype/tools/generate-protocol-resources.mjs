const responseVectors = Object.entries(sessionFixtureDocument.responses).map(([name, packet]) => ({
  name,
  packet_size: packet.packet_size,
  opcode: packet.opcode,
  sequence: packet.sequence,
  body_hex: packet.body_hex,
}));
if (requestVectors.length !== 4 || responseVectors.length !== 6 ||
    sessionFixtureDocument.warning?.includes('redacted') !== true ||
    JSON.stringify(sessionFixtureDocument).includes('plaintext_body_hex') ||
    JSON.stringify(sessionFixtureDocument).includes('encoded_frame_hex')) {
  throw new Error('Fixtures de sessão ausentes ou contêm campos de requisição não redigidos.');
}
